// src/tokens.json (DTCG) -> src/tokens.css. No dependencies: ~150 tokens and one
// output target do not need a token pipeline (ADR-0040, rejected alternatives).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "src", "tokens.json");
const target = join(here, "..", "src", "tokens.css");

// Custom-property prefix per top-level group. Colours keep their bare names
// (--ink, --brand) because the stylesheet has used them since the first screen.
const PREFIXES = {
  color: "",
  space: "space-",
  radius: "radius-",
  size: "size-",
  shadow: "shadow-",
  font: "font-",
  type: "text-",
  border: "border-",
  z: "z-",
  motion: "motion-",
  opacity: "opacity-",
};
// @media cannot read var(): these are documented in a comment, never declared.
const COMMENT_ONLY = new Set(["breakpoint"]);
const OUTDOOR = "carnival.outdoor";

const quote = (family) => (/[^a-zA-Z0-9-]/.test(family) ? `"${family}"` : family);
const render = (value) => (Array.isArray(value) ? value.map(quote).join(", ") : String(value));

/** @returns {{name: string, value: string, outdoor?: string}[]} */
function collect(tokens) {
  const out = [];
  for (const [group, members] of Object.entries(tokens)) {
    if (group.startsWith("$") || COMMENT_ONLY.has(group)) continue;
    const prefix = PREFIXES[group];
    if (prefix === undefined) throw new Error(`tokens.json: unknown group "${group}"`);
    for (const [name, token] of Object.entries(members)) {
      if (name.startsWith("$")) continue;
      if (token?.$value === undefined) {
        throw new Error(`tokens.json: ${group}.${name} has no $value`);
      }
      out.push({
        name: `--${prefix}${name}`,
        value: render(token.$value),
        outdoor: token.$extensions?.[OUTDOOR],
      });
    }
  }
  return out;
}

const json = JSON.parse(readFileSync(source, "utf8"));
const tokens = collect(json);
const breakpoints = Object.entries(json.breakpoint ?? {})
  .filter(([name]) => !name.startsWith("$"))
  .map(([name, token]) => `   ${name}: ${token.$value}`)
  .join("\n");
const declare = (list, indent) =>
  list.map(({ name, value }) => `${indent}${name}: ${value};`).join("\n");
const overrides = tokens
  .filter((t) => t.outdoor !== undefined)
  .map((t) => ({ name: t.name, value: t.outdoor }));

const css = `/* GENERATED by scripts/generate-tokens.mjs from src/tokens.json — do not edit.
   Regenerate with \`npm run generate:tokens\` (ADR-0040 §1). */

/* Breakpoints, written literally in styles.css because @media cannot read var():
${breakpoints} */

@layer base {
  :root {
${declare(tokens, "    ")}
  }

  /* Outdoor / high contrast (ADR-0040 §6): a deliberate in-app choice, and the
     same overrides for anyone whose device already asks for more contrast. */
  [data-theme="outdoor"] {
${declare(overrides, "    ")}
  }

  @media (prefers-contrast: more) {
    :root {
${declare(overrides, "      ")}
    }
  }
}
`;

writeFileSync(target, css);
process.stdout.write(
  `tokens.css: ${tokens.length} tokens, ${overrides.length} outdoor overrides\n`,
);
